// Hands the published outputs to their consumers:
//
//   bun scripts/export.ts --app <dir> [--website <public dir>] [--published out/publish]
//
// --app writes two files the app bundles: art.generated.ts (the class
// shapes and liveries, with their types, for the app's own flat drawing
// while a render loads or when it can't) and renders.generated.json (the
// manifest). --website copies the WebPs into <public dir>/trains/.
// Nothing here is imported by anyone: consumers get files.

import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

import { fleet, generic } from '../classes/fleet';
import { BOGIES, COUPLERS } from '../model/gear';
import { liveries, neutral } from '../liveries';

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

const root = join(import.meta.dir, '..');
const published = resolve(arg('published') ?? join(root, 'out', 'publish'));
const app = arg('app');
const website = arg('website');

// Lengths to the millimetre are plenty for a drawing.
const round = (_: string, v: unknown) => (typeof v === 'number' ? Math.round(v * 1000) / 1000 : v);

if (app) {
  const dir = resolve(app);
  mkdirSync(dir, { recursive: true });
  // The 3D-only parts of a class (its form) stay here: the app draws in 2D.
  const flat = Object.fromEntries(Object.entries(fleet).map(([code, { form: _form, ...art }]) => [code, art]));
  const { form: _form, ...flatGeneric } = generic;
  // types.ts imports its bogie and coupler type names from gear.ts; the
  // app gets one self-contained file, so those come inline as plain names.
  const types = readFileSync(join(root, 'model', 'types.ts'), 'utf8')
    .replace(/^import type \{ BogieType, CouplerType \} from '\.\/gear';\n/m, '')
    .concat(
      `\n/** Bogie and coupler type names (model/gear.ts). */\nexport type BogieType = ${Object.keys(BOGIES).map((k) => `'${k}'`).join(' | ')};\n`,
      `export type CouplerType = ${Object.keys(COUPLERS).map((k) => `'${k}'`).join(' | ')};\n`,
    );
  const module = [
    '// Generated by trainiac-renders (scripts/export.ts) from its classes and',
    '// liveries. Do not edit: change them there and export again.',
    '',
    types.trim(),
    '',
    // The data was type-checked where it was built; spec fields the drawing
    // doesn't read (a door's transom height, say) ride along untyped.
    `export const fleet = ${JSON.stringify(flat, round)} as unknown as Record<string, ClassArt>;`,
    '',
    `export const generic = ${JSON.stringify(flatGeneric, round)} as unknown as ClassArt;`,
    '',
    `export const liveries = ${JSON.stringify(liveries, round)} as unknown as Record<string, Record<string, Livery>>;`,
    '',
    `export const neutral: Livery = ${JSON.stringify(neutral)};`,
    '',
  ].join('\n');
  writeFileSync(join(dir, 'art.generated.ts'), module);
  const manifest = join(published, 'manifest.json');
  if (existsSync(manifest)) {
    writeFileSync(join(dir, 'renders.generated.json'), readFileSync(manifest));
    console.log(`app: wrote ${dir}/art.generated.ts and renders.generated.json`);
  } else {
    console.log(`app: wrote ${dir}/art.generated.ts; nothing published yet for renders.generated.json (run scripts/publish.ts)`);
  }
}

if (website) {
  const dir = join(resolve(website), 'trains');
  // Refuse before deleting anything when there is nothing to copy in.
  if (!existsSync(join(published, 'trains'))) throw new Error(`website: nothing published in ${published}/trains (run scripts/publish.ts, or pass --published)`);
  rmSync(dir, { recursive: true, force: true });
  cpSync(join(published, 'trains'), dir, { recursive: true });
  console.log(`website: copied the renders to ${dir}`);
}
